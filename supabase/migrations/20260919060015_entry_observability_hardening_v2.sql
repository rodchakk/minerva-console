
create table if not exists public.entry_performance_events (
  id bigint generated by default as identity primary key,
  created_at timestamptz not null default now(),
  community_id uuid null references public.communities(id) on delete set null,
  actor_id uuid null references auth.users(id) on delete set null,
  source_surface text not null,
  metric_name text not null,
  duration_ms integer not null,
  status text not null default 'success',
  error_code text null,
  platform text null,
  app_version text null,
  route text null,
  metadata jsonb not null default '{}'::jsonb,
  constraint entry_performance_events_duration_ck check (duration_ms between 0 and 600000),
  constraint entry_performance_events_status_ck check (status in ('success','failed')),
  constraint entry_performance_events_surface_ck check (char_length(source_surface) between 1 and 64),
  constraint entry_performance_events_metric_ck check (char_length(metric_name) between 1 and 96)
);

create index if not exists idx_entry_performance_events_created_at
  on public.entry_performance_events (created_at desc);
create index if not exists idx_entry_performance_events_metric_created
  on public.entry_performance_events (metric_name, created_at desc);
create index if not exists idx_entry_performance_events_community_created
  on public.entry_performance_events (community_id, created_at desc);

alter table public.entry_performance_events enable row level security;
revoke all on table public.entry_performance_events from public, anon, authenticated;
grant select, insert, update, delete on table public.entry_performance_events to service_role;

create table if not exists public.entry_observability_incidents (
  id uuid primary key default gen_random_uuid(),
  fingerprint text not null,
  scope_key text not null,
  community_id uuid null references public.communities(id) on delete set null,
  capability text not null,
  event_type text not null,
  error_code text null,
  severity text not null,
  status text not null default 'open',
  first_seen_at timestamptz not null default now(),
  last_seen_at timestamptz not null default now(),
  resolved_at timestamptz null,
  occurrence_count bigint not null default 1,
  last_details jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint entry_observability_incidents_severity_ck
    check (severity in ('INFO','WARNING','ERROR','CRITICAL')),
  constraint entry_observability_incidents_status_ck
    check (status in ('open','resolved'))

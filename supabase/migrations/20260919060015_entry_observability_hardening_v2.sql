create or replace function public.sa_get_entry_observability_v3(
  p_starts_at timestamptz,
  p_ends_at timestamptz default now(),
  p_community_id uuid default null
)
returns jsonb
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_start timestamptz := coalesce(p_starts_at,now()-interval '24 hours');
  v_end timestamptz := coalesce(p_ends_at,now());
  v_result jsonb;
  v_admin_flow jsonb;
  v_flows jsonb;
  v_incidents jsonb;
  v_perf jsonb;
  v_infra jsonb;
  v_readiness jsonb;
  v_history jsonb;
  v_status text;
begin
  if not public.is_superadmin() then
    raise exception 'Superadmin access required' using errcode='42501';
  end if;
  if v_end<=v_start or v_end-v_start>interval '31 days' then
    raise exception 'Invalid observability time range' using errcode='22023';
  end if;

  v_result := public.sa_get_entry_observability_v2(v_start,v_end,p_community_id);

  with a as (
    select
      count(*)::integer as evidence_count,
      count(*) filter(where s.event_type='ADMIN_OPERATION_SUCCEEDED')::integer as success_count,
      count(*) filter(where s.event_type='ADMIN_OPERATION_FAILED')::integer as failure_count,
      max(s.created_at) filter(where s.event_type='ADMIN_OPERATION_SUCCEEDED') as last_success_at,
      max(s.created_at) as last_seen_at,
      percentile_cont(0.95) within group (
        order by public._entry_observability_jsonb_integer_v1(s.details,'duration_ms')
      ) filter(where public._entry_observability_jsonb_integer_v1(s.details,'duration_ms') is not null) as p95
    from public.system_event_log s
    where s.created_at>=v_start and s.created_at<v_end
      and s.event_type in ('ADMIN_OPERATION_SUCCEEDED','ADMIN_OPERATION_FAILED')
      and (
        p_community_id is null
        or s.community_id=p_community_id
      )
  )
  select jsonb_build_object(
    'key','administration',
    'label','Administration',
    'status',case when evidence_count=0 then 'idle'
      else public._entry_observability_flow_status_v1(success_count,failure_count,last_success_at,evidence_count) end,
    'success_count',success_count,
    'failure_count',failure_count,
    'evidence_count',evidence_count,
    'last_success_at',last_success_at,
    'last_seen_at',last_seen_at,
    'p95_latency_ms',round(p95::numeric,0),
    'health_mode','workload'
  ) into v_admin_flow from a;

  v_flows := coalesce(v_result->'critical_flows','[]'::jsonb) || jsonb_build_array(v_admin_flow);

  select coalesce(jsonb_agg(x.payload order by x.ordinal),'[]'::jsonb)
  into v_incidents
  from (
    select e.value as payload,e.ordinality::integer as ordinal
    from jsonb_array_elements(coalesce(v_result->'incidents','[]'::jsonb)) with ordinality e(value,ordinality)
    union all
    select
      jsonb_build_object(
        'fingerprint',i.fingerprint,
        'severity',i.severity,
        'source','incident_monitor',
        'event_type',i.event_type,
        'error_code',i.error_code,
        'occurrence_count',i.occurrence_count,
        'affected_community_count',case when i.community_id is null then 0 else 1 end,
        'first_seen_at',i.first_seen_at,
        'last_seen_at',i.last_seen_at,
        'explanation',case
          when i.event_type='COMMUNICATIONS_GUARD_PUSH_UNAVAILABLE'
            then 'Active guards exist, but none currently have a registered mobile push token.'
          when i.event_type='COMMUNICATIONS_QUEUE_STUCK'
            then 'Communication work has remained pending or processing beyond the expected queue window.'
          when i.event_type='OCR_QUEUE_STUCK'
            then 'Vision work has remained pending or processing beyond the expected queue window.'
          when i.event_type='CRON_JOB_FAILED'
            then 'A scheduled ENTRY background job latest run failed.'
          else 'A current ENTRY monitor detected an operational condition that needs review.'
        end,
        'communities',case when i.community_id is null then '[]'::jsonb else jsonb_build_array(
          jsonb_build_object(
            'community_id',i.community_id,
            'community_name',coalesce(c.name,'Unknown community'),
            'occurrence_count',i.occurrence_count
          )
        ) end
      ),
      1000 + row_number() over(order by i.severity desc,i.last_seen_at desc)
    from public.entry_observability_incidents i
    left join public.communities c on c.id=i.community_id
    where i.status='open'
      and (p_community_id is null or i.community_id=p_community_id or i.community_id is null)
      and not exists (
        select 1
        from jsonb_array_elements(coalesce(v_result->'incidents','[]'::jsonb)) b
        where b->>'fingerprint'=i.fingerprint
      )
  ) x;

  with perf as (
    select *
    from public.entry_performance_events p
    where p.created_at>=v_start and p.created_at<v_end
      and (p_community_id is null or p.community_id=p_community_id)
  ),
  total as (
    select
      count(*)::integer as event_count,
      count(*) filter(where status='failed')::integer as failed_count,
      percentile_cont(0.50) within group(order by duration_ms) as p50,
      percentile_cont(0.95) within group(order by duration_ms) as p95,
      percentile_cont(0.99) within group(order by duration_ms) as p99,
      max(created_at) as last_seen_at
    from perf
  ),
  metric_rows as (
    select
      source_surface,metric_name,platform,app_version,
      count(*)::integer as event_count,
      count(*) filter(where status='failed')::integer as failed_count,
      percentile_cont(0.50) within group(order by duration_ms) as p50,
      percentile_cont(0.95) within group(order by duration_ms) as p95,
      percentile_cont(0.99) within group(order by duration_ms) as p99,
      max(created_at) as last_seen_at
    from perf
    group by source_surface,metric_name,platform,app_version
  )
  select jsonb_build_object(
    'summary',jsonb_build_object(
      'event_count',t.event_count,
      'failed_count',t.failed_count,
      'p50_ms',round(t.p50::numeric,0),
      'p95_ms',round(t.p95::numeric,0),
      'p99_ms',round(t.p99::numeric,0),
      'last_seen_at',t.last_seen_at
    ),
    'metrics',coalesce((
      select jsonb_agg(jsonb_build_object(
        'surface',m.source_surface,
        'metric',m.metric_name,
        'platform',m.platform,
        'app_version',m.app_version,
        'event_count',m.event_count,
        'failed_count',m.failed_count,
        'p50_ms',round(m.p50::numeric,0),
        'p95_ms',round(m.p95::numeric,0),
        'p99_ms',round(m.p99::numeric,0),
        'last_seen_at',m.last_seen_at
      ) order by m.event_count desc,m.source_surface,m.metric_name)
      from (select * from metric_rows order by event_count desc limit 24) m
    ),'[]'::jsonb)
  )
  into v_perf
  from total t;

  with latest_runs as (
    select
      j.jobid,j.jobname,j.schedule,j.active,
      d.status,d.start_time,d.end_time,d.return_message,
      row_number() over(partition by j.jobid order by d.start_time desc) as rn
    from cron.job j
    left join cron.job_run_details d on d.jobid=j.jobid
    where j.active=true
  ),
  queues as (
    select 'communications'::text as capability,'Mobile push queue'::text as name,
      count(*) filter(where q.status in ('pending','processing'))::integer as open_count,
      count(*) filter(where q.status='failed')::integer as failed_count,
      min(q.created_at) filter(where q.status in ('pending','processing')) as oldest_open_at
    from public.community_message_push_queue q
    where p_community_id is null or q.community_id=p_community_id
    union all
    select 'vision_recognition','OCR queue',
      count(*) filter(where q.status in ('PENDING','PROCESSING'))::integer,
      count(*) filter(where q.status='FAILED')::integer,
      min(q.created_at) filter(where q.status in ('PENDING','PROCESSING'))
    from public.plate_ocr_queue q
    join public.entry_logs el on el.id=q.entry_log_id
    where p_community_id is null or el.community_id=p_community_id
    union all
    select 'onboarding','Activation queue',
      count(*) filter(where q.status in ('pending','invited'))::integer,
      0,
      min(q.created_at) filter(where q.status in ('pending','invited'))
    from public.resident_activation_queue q
    where p_community_id is null or q.community_id=p_community_id
  ),
  db as (
    select
      numbackends as connections,
      deadlocks,
      conflicts,
      stats_reset,
      case when blks_hit+blks_read=0 then null
        else round((blks_hit::numeric/(blks_hit+blks_read))*100,2) end as cache_hit_percent
    from pg_stat_database where datname=current_database()
  )
  select jsonb_build_object(
    'workers',coalesce((
      select jsonb_agg(jsonb_build_object(
        'name',r.jobname,
        'schedule',r.schedule,
        'status',coalesce(r.status,'unknown'),
        'last_started_at',r.start_time,
        'last_finished_at',r.end_time
      ) order by r.jobname)
      from latest_runs r where r.rn=1
    ),'[]'::jsonb),
    'queues',coalesce((
      select jsonb_agg(jsonb_build_object(
        'capability',q.capability,
        'name',q.name,
        'open_count',q.open_count,
        'failed_count',q.failed_count,
        'oldest_open_at',q.oldest_open_at
      ) order by q.name)
      from queues q
    ),'[]'::jsonb),
    'database',(select jsonb_build_object(
      'connections',d.connections,
      'deadlocks',d.deadlocks,
      'conflicts',d.conflicts,
      'cache_hit_percent',d.cache_hit_percent,
      'stats_reset',d.stats_reset
    ) from db d)
  ) into v_infra;

  with selected as (
    select c.id,c.name
    from public.communities c
    where coalesce(c.is_active,false)=true
      and (p_community_id is null or c.id=p_community_id)
  ),
  members as (
    select
      s.id as community_id,s.name,
      count(distinct cm.user_id) filter(where cm.role::text='RESIDENT' and cm.is_active=true) as active_residents,
      count(distinct upt.user_id) filter(where cm.role::text='RESIDENT' and cm.is_active=true and upt.user_id is not null) as push_residents,
      count(distinct cm.user_id) filter(where cm.role::text='GUARD' and cm.is_active=true) as active_guards,
      count(distinct upt.user_id) filter(where cm.role::text='GUARD' and cm.is_active=true and upt.user_id is not null) as push_guards
    from selected s
    left join public.community_members cm on cm.community_id=s.id
    left join public.user_push_tokens upt
      on upt.user_id=cm.user_id and upt.community_id=cm.community_id and upt.is_active=true
    group by s.id,s.name
  ),
  rollout as (
    select
      s.id as community_id,
      (select count(*) from public.resident_activation_queue q where q.community_id=s.id and q.status='activated') as activated_residents,
      (select count(*) from public.visit_passes vp where vp.community_id=s.id) as passes_created,
      (select count(*) from public.entry_logs el where el.community_id=s.id) as gate_accesses,
      (select count(*) from public.community_messages m where m.community_id=s.id and m.deleted_at is null) as messages_published
    from selected s
  )
  select jsonb_build_object(
    'communities',coalesce(jsonb_agg(jsonb_build_object(
      'community_id',m.community_id,
      'community_name',m.name,
      'active_residents',m.active_residents,
      'push_ready_residents',m.push_residents,
      'active_guards',m.active_guards,
      'push_ready_guards',m.push_guards,
      'activated_residents',r.activated_residents,
      'passes_created',r.passes_created,
      'gate_accesses',r.gate_accesses,
      'messages_published',r.messages_published
    ) order by m.name),'[]'::jsonb)
  )
  into v_readiness
  from members m
  join rollout r on r.community_id=m.community_id;

  select coalesce(jsonb_agg(jsonb_build_object(
    'id',i.id,
    'fingerprint',i.fingerprint,
    'capability',i.capability,
    'event_type',i.event_type,
    'error_code',i.error_code,
    'severity',i.severity,
    'status',i.status,
    'community_id',i.community_id,
    'community_name',c.name,
    'first_seen_at',i.first_seen_at,
    'last_seen_at',i.last_seen_at,
    'resolved_at',i.resolved_at,
    'occurrence_count',i.occurrence_count,
    'details',i.last_details
  ) order by coalesce(i.resolved_at,i.last_seen_at) desc),'[]'::jsonb)
  into v_history
  from public.entry_observability_incidents i
  left join public.communities c on c.id=i.community_id
  where (p_community_id is null or i.community_id=p_community_id or i.community_id is null)
    and (
      i.status='open'
      or coalesce(i.resolved_at,i.last_seen_at)>=v_start
    );

  v_result := jsonb_set(v_result,'{critical_flows}',v_flows,true);
  v_result := jsonb_set(v_result,'{incidents}',coalesce(v_incidents,'[]'::jsonb),true);
  v_result := jsonb_set(v_result,'{performance}',coalesce(v_perf,'{}'::jsonb),true);
  v_result := jsonb_set(v_result,'{infrastructure}',coalesce(v_infra,'{}'::jsonb),true);
  v_result := jsonb_set(v_result,'{readiness}',coalesce(v_readiness,'{}'::jsonb),true);
  v_result := jsonb_set(v_result,'{incident_history}',coalesce(v_history,'[]'::jsonb),true);

  select case
    when exists(select 1 from jsonb_array_elements(v_flows) f where f->>'status'='down') then 'down'
    when exists(select 1 from jsonb_array_elements(coalesce(v_incidents,'[]'::jsonb)) i where i->>'severity' in ('CRITICAL','ERROR')) then 'degraded'
    when exists(select 1 from jsonb_array_elements(v_flows) f where f->>'status'='degraded') then 'degraded'
    when exists(select 1 from jsonb_array_elements(v_flows) f where f->>'status'='unknown') then 'unknown'
    else 'healthy'
  end into v_status;

  v_result := jsonb_set(v_result,'{summary,system_status}',to_jsonb(v_status),true);
  return v_result;
end;
$$;


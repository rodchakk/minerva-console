create index if not exists idx_entry_observability_incidents_community
  on public.entry_observability_incidents (community_id, status, last_seen_at desc);

alter table public.entry_observability_incidents enable row level security;
revoke all on table public.entry_observability_incidents from public, anon, authenticated;

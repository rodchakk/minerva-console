create or replace function public.record_entry_admin_operation_v1(
  p_operation text,
  p_status text,
  p_duration_ms integer default null,
  p_error_code text default null
)
returns uuid
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_actor uuid := auth.uid();
  v_community uuid;
  v_id uuid;
  v_operation text := left(regexp_replace(coalesce(p_operation,''), '[^a-zA-Z0-9_.:-]+', '_', 'g'), 96);
  v_status text := case when lower(coalesce(p_status,''))='success' then 'success' else 'failed' end;
  v_error text := nullif(left(regexp_replace(coalesce(p_error_code,''), '[^a-zA-Z0-9_.:-]+', '_', 'g'),96),'');
begin
  if v_actor is null then
    raise exception 'Authentication required' using errcode='42501';
  end if;

  select cm.community_id into v_community
  from public.community_members cm
  where cm.user_id=v_actor
    and cm.is_active=true
    and cm.role::text in ('ADMIN','GUARD')
  order by case cm.role::text when 'ADMIN' then 1 else 2 end, cm.created_at desc
  limit 1;

  if v_community is null then
    raise exception 'Admin or guard membership required' using errcode='42501';
  end if;

  insert into public.system_event_log (
    severity,module,event_type,message,details,community_id,user_id,actor_id,source
  )
  values (
    case when v_status='success' then 'INFO' else 'ERROR' end,
    'administration',
    case when v_status='success' then 'ADMIN_OPERATION_SUCCEEDED' else 'ADMIN_OPERATION_FAILED' end,
    case when v_status='success' then 'ENTRY administration operation succeeded' else 'ENTRY administration operation failed' end,
    jsonb_strip_nulls(jsonb_build_object(
      'status',v_status,
      'operation',v_operation,
      'duration_ms',case when p_duration_ms between 0 and 600000 then p_duration_ms else null end,
      'error_code',v_error,
      'error_fingerprint',case when v_status='failed' then 'administration:' || lower(v_operation) || ':' || lower(coalesce(v_error,'failed')) else null end
    )),
    v_community,v_actor,v_actor,'entry_web'
  )
  returning id into v_id;

  return v_id;
end;
$$;

revoke all on function public.record_entry_admin_operation_v1(text,text,integer,text) from public, anon;
grant execute on function public.record_entry_admin_operation_v1(text,text,integer,text)
  to authenticated, service_role;

create or replace function public.get_dashboard_stats()
returns table(
  accesses_today bigint,
  active_users bigint,
  units bigint,
  active_passes bigint
)
language plpgsql
stable
security definer
set search_path = public, pg_temp
as $$
declare
  v_user uuid := auth.uid();
  v_community uuid;
  v_tz text := 'America/Tegucigalpa';
  v_start timestamptz;
  v_end timestamptz;
begin
  select cm.community_id into v_community
  from public.community_members cm
  where cm.user_id=v_user
    and cm.is_active=true
    and cm.role::text in ('ADMIN','GUARD')
  order by case cm.role::text when 'ADMIN' then 1 else 2 end
  limit 1;

  if v_community is null then
    raise exception 'ADMIN or GUARD role required' using errcode='42501';
  end if;

  select coalesce(nullif(cs.timezone,''),'America/Tegucigalpa')
  into v_tz
  from public.community_settings cs
  where cs.community_id=v_community;

  v_tz := coalesce(v_tz,'America/Tegucigalpa');
  v_start := date_trunc('day', now() at time zone v_tz) at time zone v_tz;
  v_end := v_start + interval '1 day';

  return query
  select
    (select count(*) from public.entry_logs el
      where el.community_id=v_community and el.action_at>=v_start and el.action_at<v_end),
    (select count(*) from public.community_members cm
      where cm.community_id=v_community and cm.is_active=true),
    (select count(*) from public.houses h
      where h.community_id=v_community),
    (select count(*) from public.visit_passes vp
      where vp.community_id=v_community and vp.status::text in ('ACTIVE','CHECKED_IN'));
end;
$$;

revoke all on function public.get_dashboard_stats() from public, anon;
grant execute on function public.get_dashboard_stats() to authenticated, service_role;

create or replace function public.admin_list_access_history_v2(
  p_community_id uuid,
  p_limit integer default 20,
  p_offset integer default 0,
  p_search text default null,
  p_type text default null,
  p_method text default null,
  p_evidence text default null,
  p_start_at timestamptz default null,
  p_end_at timestamptz default null
)
returns table(
  id uuid,
  created_at timestamptz,
  action text,
  type text,
  visitor_name text,
  unit_label text,
  method text,
  plate text,
  has_evidence boolean
)
language plpgsql
security definer
set search_path = public, pg_temp
as $$
declare
  v_limit integer := least(greatest(coalesce(p_limit,20),1),51);
  v_offset integer := greatest(coalesce(p_offset,0),0);
  v_search text := nullif(lower(btrim(coalesce(p_search,''))),'');
  v_type text := nullif(upper(btrim(coalesce(p_type,''))),'');
  v_method text := nullif(upper(btrim(coalesce(p_method,''))),'');
  v_evidence text := nullif(upper(btrim(coalesce(p_evidence,''))),'');
begin
  if p_community_id is null then
    raise exception 'p_community_id is required' using errcode='22023';
  end if;

  if not exists (
    select 1 from public.community_members cm
    where cm.user_id=auth.uid()
      and cm.community_id=p_community_id
      and cm.is_active=true
      and cm.role::text in ('ADMIN','GUARD')
  ) then
    raise exception 'ADMIN or GUARD role required' using errcode='42501';
  end if;

  return query
  with base as (
    select
      el.id,
      el.action_at as created_at,
      el.action::text as action,
      coalesce(
        vp.pass_type::text,
        case
          when el.frequent_visitor_id is not null then 'FREQUENT'
          when el.visit_group_id is not null and vg.group_type::text='EVENT' then 'EVENT'
          when el.visit_group_member_id is not null or el.visit_group_id is not null then 'GROUP'
          when el.manual_entry_id is not null then 'MANUAL'
          else 'UNKNOWN'
        end
      ) as type,
      coalesce(vp.visitor_name,afv.full_name,vgm.visitor_name,me.manual_entry_name,'Sin nombre') as visitor_name,
      coalesce(h.house_label,me.destination_label,'Sin unidad') as unit_label,
      el.method::text as method,
      coalesce(el.vehicle_plate_text,vp.vehicle_plate) as plate,
      (el.photo_path is not null or el.vehicle_photo_path is not null) as has_evidence
    from public.entry_logs el
    left join public.houses h on h.id=el.house_id
    left join public.visit_passes vp on vp.id=el.pass_id
    left join public.authorized_frequent_visitors afv on afv.id=el.frequent_visitor_id
    left join public.visit_group_members vgm on vgm.id=el.visit_group_member_id
    left join public.visit_groups vg on vg.id=el.visit_group_id
    left join public.manual_entries me on me.id=el.manual_entry_id
    where el.community_id=p_community_id
      and (p_start_at is null or el.action_at>=p_start_at)
      and (p_end_at is null or el.action_at<=p_end_at)
  )
  select b.*
  from base b
  where (v_type is null or v_type='ALL' or upper(b.type)=v_type)
    and (v_method is null or v_method='ALL' or upper(b.method)=v_method)
    and (
      v_evidence is null or v_evidence='ALL'
      or (v_evidence='WITH_EVIDENCE' and b.has_evidence)
      or (v_evidence='WITHOUT_EVIDENCE' and not b.has_evidence)
    )
    and (
      v_search is null
      or lower(coalesce(b.visitor_name,'') || ' ' || coalesce(b.unit_label,'') || ' ' ||
               coalesce(b.plate,'') || ' ' || coalesce(b.method,'') || ' ' || coalesce(b.type,'')) like '%' || v_search || '%'
    )
  order by b.created_at desc
  limit v_limit
  offset v_offset;
end;
$$;

